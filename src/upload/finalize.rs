/// Whether this call completed new durable work or replayed it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FinalizeDisposition {
    /// New durable work and the Finalized lifecycle outcome committed.
    Finalized,
    /// The exact logical durable outcome was already committed.
    ExistingOutcome,
}

/// Safe finalization result.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct FinalizeUploadOutcome {
    disposition: FinalizeDisposition,
    durable: DurableUpload,
    revision: UploadRevision,
}

impl FinalizeUploadOutcome {
    /// Returns whether durable work was new or replayed.
    #[must_use]
    pub const fn disposition(&self) -> FinalizeDisposition {
        self.disposition
    }

    /// Returns the durable logical upload.
    #[must_use]
    pub const fn durable(&self) -> &DurableUpload {
        &self.durable
    }

    /// Returns the authoritative Finalized upload revision.
    #[must_use]
    pub const fn revision(&self) -> UploadRevision {
        self.revision
    }
}

/// Finalization coordinator preserving action, upload, policy, and retry authority.
pub struct UploadFinalizationService {
    authority: Arc<UploadService>,
    evidence: Arc<dyn UploadValidationStore>,
    finalizer: Arc<dyn UploadFinalizer>,
}

impl UploadFinalizationService {
    /// Creates a service over persistent authority, evidence, and durable host work.
    #[must_use]
    pub fn new(
        authority: Arc<UploadService>,
        evidence: Arc<dyn UploadValidationStore>,
        finalizer: Arc<dyn UploadFinalizer>,
    ) -> Self {
        Self {
            authority,
            evidence,
            finalizer,
        }
    }

    /// Reauthorizes and idempotently finalizes one Ready upload.
    pub async fn finalize(
        &self,
        context: &TrustedLiveRequestContext,
        request: FinalizeUploadRequest,
        now: UnixMillis,
    ) -> Result<FinalizeUploadOutcome, UploadError> {
        if request.action.component() != context.mount().component()
            || request.action.action() != request.policy.finalize_action()
        {
            return Err(UploadError::new(UploadErrorKind::AuthorizationDenied));
        }
        let finalizing_revision = request.ready_revision.checked_next()?;
        let finalized_revision = finalizing_revision.checked_next()?;
        let record = self
            .authority
            .trusted_status(
                context,
                request.field.clone(),
                request.handle.clone(),
                UploadControlKind::BeginFinalize,
                now,
            )
            .await?;
        let coherent_state = match record.state() {
            UploadState::Ready => record.revision() == request.ready_revision,
            UploadState::Finalizing => record.revision() == finalizing_revision,
            UploadState::Finalized => record.revision() == finalized_revision,
            _ => false,
        };
        if !coherent_state {
            return Err(UploadError::new(UploadErrorKind::UploadConflict));
        }
        let evidence = self
            .evidence
            .load(&request.handle)
            .await?
            .ok_or_else(|| UploadError::new(UploadErrorKind::ValidationEvidenceUnavailable))?;
        if evidence.authority() != record.authority()
            || evidence.ready_revision() != request.ready_revision
            || evidence.policy_digest() != request.policy.contract_digest()
        {
            return Err(UploadError::new(
                UploadErrorKind::ValidationEvidenceUnavailable,
            ));
        }

        let begin = self
            .authority
            .trusted_transition(
                context,
                request.field.clone(),
                UploadTransitionRequest::new(
                    request.handle.clone(),
                    request.ready_revision,
                    phase_key(&request.idempotency_key, "begin")?,
                    UploadTransition::BeginFinalize,
                ),
                now,
            )
            .await?;
        if begin.state() != UploadState::Finalizing || begin.revision() != finalizing_revision {
            return Err(UploadError::new(UploadErrorKind::UploadConflict));
        }

        let port_request = FinalizeRequest::new(
            &evidence,
            request.action.action(),
            &request.idempotency_key,
            now,
        );
        let reconciled = self.finalizer.reconcile(port_request).await?;
        if record.state() == UploadState::Finalized && reconciled.is_none() {
            return Err(UploadError::new(UploadErrorKind::ReconciliationRequired));
        }
        let (durable, existing_external) = if let Some(durable) = reconciled {
            if !durable.matches(&port_request) {
                return Err(UploadError::new(UploadErrorKind::ReconciliationRequired));
            }
            (durable, true)
        } else {
            let prepared = self.finalizer.prepare(port_request).await?;
            if !prepared.matches(&port_request) {
                if self
                    .finalizer
                    .compensate(FailedFinalize::new(
                        prepared,
                        FinalizeFailureStage::InvalidPreparation,
                    ))
                    .await
                    .is_err()
                {
                    return Err(UploadError::new(UploadErrorKind::CompensationFailed));
                }
                return Err(UploadError::new(UploadErrorKind::FinalizationFailed));
            }
            let durable = match self.finalizer.commit(prepared.clone()).await {
                Ok(durable) => durable,
                Err(error) => {
                    if self
                        .finalizer
                        .compensate(FailedFinalize::new(prepared, FinalizeFailureStage::Commit))
                        .await
                        .is_err()
                    {
                        return Err(UploadError::new(UploadErrorKind::CompensationFailed));
                    }
                    return Err(error);
                }
            };
            if !durable.matches(&port_request) {
                return Err(UploadError::new(UploadErrorKind::ReconciliationRequired));
            }
            (durable, false)
        };

        let commit = self
            .authority
            .trusted_transition(
                context,
                request.field,
                UploadTransitionRequest::new(
                    request.handle,
                    finalizing_revision,
                    phase_key(&request.idempotency_key, "commit")?,
                    UploadTransition::CommitFinalize,
                ),
                now,
            )
            .await
            .map_err(|_| UploadError::new(UploadErrorKind::ReconciliationRequired))?;
        if commit.state() != UploadState::Finalized || commit.revision() != finalized_revision {
            return Err(UploadError::new(UploadErrorKind::ReconciliationRequired));
        }
        let existing = existing_external
            || begin.disposition() == TransitionDisposition::ExistingOutcome
            || commit.disposition() == TransitionDisposition::ExistingOutcome;
        Ok(FinalizeUploadOutcome {
            disposition: if existing {
                FinalizeDisposition::ExistingOutcome
            } else {
                FinalizeDisposition::Finalized
            },
            durable,
            revision: commit.revision(),
        })
    }
}

