const MAX_FINALIZE_IDENTITY_BYTES: usize = 128;

/// Opaque idempotent host operation identity for prepared durable work.
#[derive(Clone, Eq, Hash, PartialEq)]
pub struct FinalizeToken(String);

impl FinalizeToken {
    /// Parses a bounded safe host operation identity.
    pub fn parse(value: &str) -> Result<Self, UploadError> {
        parse_finalize_identity(value).map(Self)
    }

    /// Returns the trusted operation identity for host persistence lookup.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Debug for FinalizeToken {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("<FinalizeToken>")
    }
}

