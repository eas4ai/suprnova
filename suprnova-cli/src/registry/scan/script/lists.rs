/// How a call's arguments are checked, by method or function name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Rule {
    /// The arguments at these positions are called back.
    Callbacks(&'static [usize]),
    /// A timer: the first argument must be a function.
    Timer,
    /// `setAttribute(name, value)` and friends: the name argument's index
    /// and the value argument's index.
    Attribute(usize, Option<usize>),
    /// `createElement(name)`: the name argument's index.
    Element(usize),
    /// A URL at this index must stay on the application's origin.
    Url(usize),
    /// `open`: a window URL or an `XMLHttpRequest` URL.
    Open,
    /// `location.assign` and `location.replace`, which share their names
    /// with string and object methods.
    Navigate,
    /// `customElements.define(name, class)`.
    Define,
    /// `style.setProperty(name, value)`.
    StyleProperty,
    /// `element.animate(keyframes)`: a keyframe may set a CSS property that
    /// names a resource.
    Keyframes,
}

