/// The rule for a method or global function name, when it has one.
pub fn rule_for(name: &str) -> Option<Rule> {
    ARGUMENT_RULES
        .iter()
        .find(|(rule_name, _)| *rule_name == name)
        .map(|(_, rule)| *rule)
}

/// The rule for a constructor name, when it has one.
pub fn constructor_rule_for(name: &str) -> Option<Rule> {
    CONSTRUCTOR_RULES
        .iter()
        .find(|(rule_name, _)| *rule_name == name)
        .map(|(_, rule)| *rule)
}
